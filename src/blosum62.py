def _build_blosum62_dict():
    lines = _BLOSUM62_RAW.strip().split('\n')
    header = lines[0].split()
    matrix = {}
    for line in lines[1:]:
        parts = line.split()
        row_aa = parts[0]
        scores = [int(x) for x in parts[1:]]
        for col_aa, score in zip(header, scores):
            matrix[(row_aa, col_aa)] = score
            matrix[(col_aa, row_aa)] = score
    return matrix

BLOSUM62 = _build_blosum62_dict()

def get_blosum62_score(aa1, aa2):
    '''Gets BLOSUM62 score for a substitution.'''
    aa1 = aa1.upper()
    aa2 = aa2.upper()
    if (aa1, aa2) in BLOSUM62:
        return BLOSUM62[(aa1, aa2)]
    return -4
